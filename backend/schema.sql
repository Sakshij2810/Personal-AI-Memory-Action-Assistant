
-- backend/schema.sql
-- Creates the complete database structure for Memora AI.
-- Run this file when setting up a fresh database.

-- =========================================================
-- 1. ENABLE UUID GENERATION
-- =========================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;


-- =========================================================
-- 2. USERS TABLE
-- =========================================================

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    firebase_uid TEXT UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE,
    display_name VARCHAR(255),
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- =========================================================
-- 3. MEDIA STATUS ENUM
-- =========================================================

DO $$
BEGIN
    CREATE TYPE media_status AS ENUM (
        'uploaded',
        'failed'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =========================================================
-- 4. PROCESSING STATUS ENUM
-- =========================================================

DO $$
BEGIN
    CREATE TYPE processing_status AS ENUM (
        'uploaded',
        'processing',
        'completed',
        'failed'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =========================================================
-- 5. MEDIA FILES TABLE
-- =========================================================

CREATE TABLE IF NOT EXISTS media_files (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    filename TEXT NOT NULL,
    storage_key TEXT NOT NULL UNIQUE,

    mime_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0),

    uploaded_at TIMESTAMPTZ DEFAULT NOW(),

    -- Original media status
    status media_status NOT NULL DEFAULT 'uploaded',

    -- Background processing status
    processing_status processing_status NOT NULL DEFAULT 'uploaded',

    -- Thumbnail information generated by Sharp
    thumbnail_key TEXT,
    width INTEGER,
    height INTEGER,
    format VARCHAR(20),

    -- Background processing timestamps
    processing_started_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 6. INDEXES
-- =========================================================

-- Faster queries when fetching a user's media.
CREATE INDEX IF NOT EXISTS idx_media_files_user_id
ON media_files(user_id);

-- Faster queries when sorting media by upload date.
CREATE INDEX IF NOT EXISTS idx_media_files_uploaded_at
ON media_files(uploaded_at DESC);

-- Faster queries when recovering pending media jobs.
CREATE INDEX IF NOT EXISTS idx_media_files_processing_status
ON media_files(processing_status);
