
-- backend/schema.sql
-- Creates the complete database structure for Memora AI.
-- Run this file when setting up a fresh database.

-- =========================================================
-- 1. ENABLE REQUIRED EXTENSIONS
-- =========================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS vector;


-- =========================================================
-- 2. USERS TABLE
-- =========================================================

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    firebase_uid TEXT UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE,
    display_name VARCHAR(255),
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- =========================================================
-- 3. MEDIA STATUS ENUM
-- =========================================================

DO $$
BEGIN
    CREATE TYPE media_status AS ENUM (
        'uploaded',
        'failed'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =========================================================
-- 4. THUMBNAIL PROCESSING STATUS ENUM
-- =========================================================

DO $$
BEGIN
    CREATE TYPE processing_status AS ENUM (
        'uploaded',
        'processing',
        'completed',
        'failed'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =========================================================
-- 5. AI ANALYSIS STATUS ENUM
-- =========================================================

DO $$
BEGIN
    CREATE TYPE analysis_status AS ENUM (
        'pending',
        'processing',
        'completed',
        'failed'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =========================================================
-- 6. FACE PROCESSING STATUS ENUM
-- =========================================================

DO $$
BEGIN
    CREATE TYPE face_processing_status AS ENUM (
        'pending',
        'processing',
        'completed',
        'failed'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =========================================================
-- 7. MEDIA FILES TABLE
-- =========================================================

CREATE TABLE IF NOT EXISTS media_files (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    filename TEXT NOT NULL,
    storage_key TEXT NOT NULL UNIQUE,

    mime_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0),

    uploaded_at TIMESTAMPTZ DEFAULT NOW(),

    -- Original media status
    status media_status NOT NULL DEFAULT 'uploaded',

    -- Thumbnail processing status
    processing_status processing_status NOT NULL DEFAULT 'uploaded',

    -- Thumbnail information generated by Sharp
    thumbnail_key TEXT,
    width INTEGER,
    height INTEGER,
    format VARCHAR(20),

    -- Thumbnail processing timestamps
    processing_started_at TIMESTAMPTZ,

    -- Face processing lifecycle
    face_processing_status face_processing_status
        NOT NULL DEFAULT 'pending',

    face_processing_started_at TIMESTAMPTZ,

    face_processing_attempt_count INTEGER NOT NULL DEFAULT 0
        CHECK (face_processing_attempt_count >= 0),

    face_processing_error TEXT,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 8. MEDIA FILES INDEXES
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_media_files_user_id
ON media_files(user_id);

CREATE INDEX IF NOT EXISTS idx_media_files_uploaded_at
ON media_files(uploaded_at DESC);

CREATE INDEX IF NOT EXISTS idx_media_files_processing_status
ON media_files(processing_status);

CREATE INDEX IF NOT EXISTS idx_media_files_face_processing_status
ON media_files(face_processing_status);

CREATE INDEX IF NOT EXISTS idx_media_files_face_processing_started_at
ON media_files(face_processing_started_at);


-- =========================================================
-- 9. MEDIA ANALYSIS TABLE
-- =========================================================

CREATE TABLE IF NOT EXISTS media_analysis (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- One analysis record per media file.
    media_file_id UUID NOT NULL UNIQUE
        REFERENCES media_files(id) ON DELETE CASCADE,

    -- AI-generated information
    description TEXT,

    -- Example: [{"name": "wedding", "confidence": 0.95}]
    labels JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(labels) = 'array'),

    -- AI provider information
    provider VARCHAR(50),
    model VARCHAR(100),

    -- Analysis lifecycle
    status analysis_status NOT NULL DEFAULT 'pending',

    -- Retry tracking
    attempt_count INTEGER NOT NULL DEFAULT 0
        CHECK (attempt_count >= 0),

    -- Error information
    error_message TEXT,

    -- Timestamps
    analysis_started_at TIMESTAMPTZ,
    analyzed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 10. MEDIA ANALYSIS INDEXES
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_media_analysis_status
ON media_analysis(status);

CREATE INDEX IF NOT EXISTS idx_media_analysis_updated_at
ON media_analysis(updated_at);


-- =========================================================
-- 11. DETECTED FACES TABLE
-- =========================================================

CREATE TABLE IF NOT EXISTS detected_faces (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Original media containing this face
    media_file_id UUID NOT NULL
        REFERENCES media_files(id) ON DELETE CASCADE,

    -- Face number within the original image
    face_number INTEGER NOT NULL
        CHECK (face_number > 0),

    -- Face bounding box returned by Python
    bounding_box JSONB NOT NULL
        CHECK (jsonb_typeof(bounding_box) = 'object'),

    -- YuNet detection confidence
    detection_confidence REAL NOT NULL
        CHECK (
            detection_confidence >= 0
            AND detection_confidence <= 1
        ),

    -- SFace 128-dimensional embedding
    embedding vector(128) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Prevent duplicate face numbers within one image
    UNIQUE (media_file_id, face_number)
);


-- =========================================================
-- 12. DETECTED FACES INDEXES
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_detected_faces_media_file_id
ON detected_faces(media_file_id);


-- =========================================================
-- 13. VERIFY PGVECTOR
-- =========================================================

SELECT extname, extversion
FROM pg_extension
WHERE extname = 'vector';
