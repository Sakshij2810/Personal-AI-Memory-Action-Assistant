// backend/workers/media.worker.ts

import { Worker } from "bullmq";
import bullmqRedis from "../shared/redis/bullmq-connection.js";
import pool from "../config/db.js";
import path from "node:path";
import { mkdir } from "node:fs/promises";
import sharp from "sharp";
import {
  recoverStuckProcessingJobs,
  recoverUnqueuedMediaJobs,
} from "../helpers/media.helper.js";
import { mediaStorageDir, mediaThumbnailDir } from "../config/media-storage.js";
/* One important operational point: Keep the worker running in its own terminal. Your Express server and worker will be separate running processes.
 */

//  Create BullMQ worker
export const mediaWorker = new Worker(
  "media-processing",
  /* 1. name of queue
      - It must match the queue name we used in media.queue.ts.
      - The worker doesn't need to import the queue instance itself. It connects to the same named queue through Redis.
   */

  // 2. processing function
  async (job) => {
    const { mediaId, userId, storageKey } = job.data;

    const mediaResult = await pool.query(
      `
  SELECT id
  FROM media_files
  WHERE id = $1 AND user_id = $2
  `,
      [mediaId, userId],
    );

    if (mediaResult.rowCount === 0) {
      console.log(`Media ${mediaId} was deleted. Skipping job.`);
      return { success: true, skipped: true, mediaId };
    }

    console.log(`Processing media: ${mediaId}`);

    // 1. Mark the media as processing.
    await pool.query(
      `UPDATE media_files
       SET processing_status = 'processing',
       processing_started_at = NOW(),
       updated_at = NOW()
       WHERE id = $1 AND user_id = $2`,
      [mediaId, userId],
    );

    // 2. Locate the original image.
    const originalPath = path.resolve(mediaStorageDir, storageKey);

    // 3. Prepare the thumbnail directory.
    const thumbnailDirectory = mediaThumbnailDir;

    await mkdir(thumbnailDirectory, { recursive: true });

    // 4. Extract original image metadata.
    const metadata = await sharp(originalPath).metadata();

    // 5. Generate a thumbnail.
    const thumbnailKey = `${mediaId}.webp`;
    const thumbnailPath = path.join(thumbnailDirectory, thumbnailKey);

    const thumbnailResult = await sharp(originalPath)
      .resize({
        width: 300,
        withoutEnlargement: true,
      })
      .webp({ quality: 80 })
      .toFile(thumbnailPath);

    // 6. Save processing results in PostgreSQL. -> (this should Update the same media record on every retry.)
    const updateResult = await pool.query(
      `UPDATE media_files
       SET thumbnail_key = $1,
           width = $2,
           height = $3,
           format = $4,
           processing_status = 'completed',
           processing_started_at = NULL,
           updated_at = NOW()
       WHERE id = $5 AND user_id = $6
        RETURNING id
        `,
      [
        thumbnailKey,
        metadata.width ?? null,
        metadata.height ?? null,
        metadata.format ?? null,
        mediaId,
        userId,
      ],
    );

    // The media record may have been deleted while the job was running.
    if (updateResult.rowCount === 0) {
      // The image was deleted while processing.
      // Remove the thumbnail generated by this job.

      const { unlink } = await import("node:fs/promises");

      await unlink(thumbnailPath).catch(() => {});
      console.log(`Media ${mediaId} was deleted during processing.`);
      return { success: true, skipped: true, mediaId };
    }

    console.log(`Media ${mediaId} processed successfully!`);

    // 8. Return the job result.
    return {
      success: true,
      mediaId,
      thumbnailKey,
      width: metadata.width,
      height: metadata.height,
      thumbnailSize: thumbnailResult.size,
    };
  },

  // 3. connection with redis and concurrency:1 (only perform 1 job at a time)
  {
    connection: bullmqRedis,
    concurrency: 1,
  },
);

// Connect recovery to the worker

/*
PostgreSQL status	  BullMQ state	           Recovery action
processing (stale)	Job missing	             Recreate job
processing (stale)	active	                Let BullMQ handle stalled-job detection
processing (stale)	waiting / delayed. 	   Let worker process it
processing (stale)	failed	Reconcile      PostgreSQL to failed
processing (stale)	completed	             Log inconsistency; don't blindly reprocess
*/

let isRecoveryRunning = false;

const runMediaRecovery = async () => {
  // Prevent overlapping recovery executions.
  if (isRecoveryRunning) return;
  isRecoveryRunning = true;

  try {
    await recoverUnqueuedMediaJobs();
    await recoverStuckProcessingJobs();
  } catch (error) {
    console.error("Media recovery failed:", error);
  } finally {
    isRecoveryRunning = false;
  }
};

// Worker lifecycle events

let recoveryInterval: ReturnType<typeof setInterval> | undefined;

mediaWorker.on("ready", () => {
  console.log("Media worker is ready and waiting for jobs...");

  // Run recovery immediately.
  void runMediaRecovery();

  // Repeat recovery every 30 seconds.
  if (!recoveryInterval) {
    recoveryInterval = setInterval(() => {
      void runMediaRecovery();
    }, 30_000);
  }
});

mediaWorker.on("active", (job) => {
  console.log(`Job ${job.id} is now ACTIVE`);
});

mediaWorker.on("completed", (job, result) => {
  console.log(`Job ${job.id} is now COMPLETED`);
  console.log("Result:", result);
});

mediaWorker.on("failed", async (job, error) => {
  console.error(`Job ${job?.id} FAILED:`, error.message);

  if (!job) return;

  const maxAttempts = job.opts.attempts ?? 1;

  // Check whether all attempts have been exhausted.
  if (job.attemptsMade >= maxAttempts) {
    const { mediaId, userId } = job.data;

    console.log(`All attempts exhausted for media: ${mediaId}`);

    try {
      await pool.query(
        `UPDATE media_files
         SET processing_status = 'failed',
             processing_started_at = NULL,
             updated_at = NOW()
         WHERE id = $1 AND user_id = $2`,
        [mediaId, userId],
      );

      console.log(`Media ${mediaId} marked as FAILED in PostgreSQL`);
    } catch (dbError) {
      console.error("Failed to update media status:", dbError);
    }
  } else {
    console.log(
      `Retrying job... Attempt ${job.attemptsMade} of ${maxAttempts}`,
    );
  }
});

mediaWorker.on("error", (error) => {
  console.error("Worker error:", error);
});

// This lets automated tests stop the worker and its recovery interval cleanly.
export const closeMediaWorker = async () => {
  if (recoveryInterval) {
    clearInterval(recoveryInterval);
    recoveryInterval = undefined;
  }

  await mediaWorker.close();

  console.log("Media worker closed successfully.");
};
